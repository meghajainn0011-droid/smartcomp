#!/usr/bin/env bash
# Install SmartComp on this machine: venv, editable package, user service,
# PATH entry point and the agent-facing endpoint file. Idempotent: re-running
# it re-converges the same state without touching the token or session data.
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
VENV="$REPO/.venv"
STATE_DIR="${XDG_STATE_HOME:-$HOME/.local/state}/smartcomp"
BIN_DIR="$HOME/.local/bin"

echo "== repo: $REPO"

# 1. venv with the system site packages: the heavy runtime deps (numpy, cv2,
#    mss, onnxruntime, pillow, httpx, mcp) already live in the system python
#    and the venv should reuse them, not re-download them.
if [ ! -x "$VENV/bin/python" ]; then
    python3 -m venv --system-site-packages "$VENV"
    echo "== created venv"
fi

# 2. the package itself, editable so repo changes are live after a restart.
"$VENV/bin/pip" install --quiet -e "$REPO"
echo "== package installed (editable)"

# 3. user service: starts at login, restarts on crash, X display bound.
mkdir -p "$HOME/.config/systemd/user"
cat > "$HOME/.config/systemd/user/smartcomp.service" <<UNIT
[Unit]
Description=SmartComp desktop-control MCP daemon
After=graphical-session.target

[Service]
Type=simple
WorkingDirectory=$REPO
Environment=DISPLAY=:0.0
Environment=OMP_THREAD_LIMIT=1
ExecStart=$VENV/bin/smartcomp serve
Restart=always
RestartSec=2
StandardOutput=append:/tmp/smartcomp_server.log
StandardError=append:/tmp/smartcomp_server.log

[Install]
WantedBy=default.target
UNIT
systemctl --user daemon-reload
systemctl --user enable --now smartcomp.service
echo "== service enabled and (re)started"

# 4. the CLI on PATH for humans and scripts.
mkdir -p "$BIN_DIR"
ln -sf "$VENV/bin/smartcomp" "$BIN_DIR/smartcomp"
echo "== cli on PATH: $BIN_DIR/smartcomp"

# 5. wait for the daemon, then publish the endpoint any agent connects with.
TOKEN_FILE="$STATE_DIR/token"
for _ in $(seq 1 45); do
    sleep 2
    [ -s "$TOKEN_FILE" ] || continue
    CODE=$(curl -s -m 2 -o /dev/null -w "%{http_code}" \
        -H "Authorization: Bearer $(cat "$TOKEN_FILE")" \
        http://127.0.0.1:8791/mcp 2>/dev/null || true)
    # 405 (sessionless GET) or 406 (Accept without event-stream) both mean the
    # MCP endpoint answered, i.e. the daemon is up and the token is right.
    { [ "$CODE" = "405" ] || [ "$CODE" = "406" ]; } && break
done
mkdir -p "$STATE_DIR"
chmod 700 "$STATE_DIR"
chmod 600 "$TOKEN_FILE" 2>/dev/null || true

TOKEN=$(cat "$TOKEN_FILE")
cat > "$STATE_DIR/mcp.json" <<JSON
{
  "name": "smartcomp",
  "transport": "streamable-http",
  "url": "http://127.0.0.1:8791/mcp",
  "headers": { "Authorization": "Bearer $TOKEN" },
  "token_path": "$TOKEN_FILE",
  "tools": "the live tool registry; regenerated by the daemon at every startup",
  "docs": "$REPO/README.md"
}
JSON
chmod 600 "$STATE_DIR/mcp.json"
echo "== endpoint file: $STATE_DIR/mcp.json (mode 600; the daemon rewrites it with the live tool list at every startup)"

echo
echo "Done. Any MCP agent can connect with:"
echo "  url:     http://127.0.0.1:8791/mcp"
echo "  header:  Authorization: Bearer \$(cat $TOKEN_FILE)"
echo "  or point it at: $STATE_DIR/mcp.json"
systemctl --user is-active smartcomp.service
